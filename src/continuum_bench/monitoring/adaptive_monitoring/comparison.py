#!/usr/bin/env python3
"""Compare recorded baseline/recovery cohorts without inventing missing outcomes.

Reporting reads archived evidence; it never deploys workers or reruns experiments.
"""
from __future__ import annotations

import argparse
from collections import defaultdict
import csv
from datetime import datetime
import json
import math
from pathlib import Path
import re
import shutil
import statistics

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np
from matplotlib.patches import Patch

COLORS = {'Baseline': '#777777', 'After adaptation': '#0072B2'}


def read_csv(path):
    if not path.exists():
        return []
    with path.open(newline='') as handle:
        return list(csv.DictReader(handle))


def write_csv(path, rows):
    if not rows:
        return
    with path.open('w', newline='') as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def number(value):
    try:
        result = float(value)
        return result if math.isfinite(result) else math.nan
    except (TypeError, ValueError):
        return math.nan


def json_rows(text):
    if not text.strip():
        return []
    try:
        value = json.loads(text)
        return value if isinstance(value, list) else [value]
    except json.JSONDecodeError:
        return [json.loads(line) for line in text.splitlines() if line.strip()]


def memory_mib(text):
    match = re.fullmatch(r'([\d.]+)\s*([A-Za-z]+)', text.split('/')[0].strip())
    if not match:
        return math.nan
    factors = {'B': 1/1048576, 'kB': 1000/1048576, 'MB': 1000000/1048576,
               'GB': 1000000000/1048576, 'KiB': 1/1024, 'MiB': 1, 'GiB': 1024}
    return float(match[1])*factors.get(match[2], math.nan)


def save_figure(fig, folder, name, manifest):
    fig.savefig(folder/name, dpi=300, bbox_inches='tight')
    plt.close(fig)
    manifest.append(name)


def comparison(directory):
    directory = Path(directory).resolve()
    decisions = json.loads((directory/'decisions.json').read_text())
    provenance = json.loads((directory/'provenance.json').read_text())
    baseline = Path(provenance['baseline'])
    if not baseline.exists():
        raise FileNotFoundError(f'Baseline evidence unavailable: {baseline}')
    figures = directory/'figures'; figures.mkdir(exist_ok=True)
    analysis = directory/'analysis'; analysis.mkdir(exist_ok=True)
    manifest, totals, concurrency_data, node_data, telemetry = [], [], [], [], []
    if (directory/'recovery-outcomes.png').exists():
        shutil.copy2(directory/'recovery-outcomes.png', figures/'recovery-outcomes.png')
        manifest.append('recovery-outcomes.png')
    notes = []
    for action in decisions:
        if 'results' not in action:
            notes.append(f"{action['scenario']} / {action['layout']}: {action['status']}; "
                         f"{action.get('decision', {}).get('reason', 'no measured recovery result')}")
            continue
        after = directory/action['results']
        attempt = after.parent.parent
        # Placement is recorded in the attempt directory generated by the supervisor.
        count = int(attempt.name.rsplit('-', 2)[1])
        before = baseline/f'placement-{count}'/action['scenario']/'measured/distributed-reasoning-scalability'
        datasets = {phase: {name: read_csv(path/filename) for name, filename in (
            ('runs','distributed-reasoning-summary.csv'), ('queries','query-scalability.csv'),
            ('nodes','node-runs.csv'))} for phase,path in [('Baseline',before),('After adaptation',after)]}
        decision = action['decision']
        operation = ' + replica on ' if decision.get('origin_retained') else ' → '
        description = f"{action['scenario']}: {decision['source']}{operation}{decision['destination']}"
        notes.append(f"{description}; {action['status']}. Deployment {action.get('deployment_seconds', 0):.1f} s; "
                     f"whole attempt {action.get('elapsed_seconds', 0)/60:.1f} min (not service recovery time).")
        reasoners = sorted({r['reasoner'] for d in datasets.values() for r in d['runs']})
        for reasoner in reasoners:
            tag = f'{attempt.name}-{reasoner}'
            groups = {(phase,layout): {kind:[r for r in data if r['layout']==layout and r['reasoner']==reasoner]
                      for kind,data in dataset.items()}
                      for phase,dataset in datasets.items() for layout in ('distributed','replicated')}
            fig, axes = plt.subplots(1,2,figsize=(11,4),layout='constrained')
            for phase,offset in [('Baseline',-.18),('After adaptation',.18)]:
                for i,layout in enumerate(('distributed','replicated')):
                    g = groups[phase,layout]
                    prepared = sum(r['status']=='completed' for r in g['runs'])
                    attempted = sum(int(r['client_requests']) for r in g['queries'])
                    failed = sum(int(r['error_count']) for r in g['queries'])
                    totals.append(dict(attempt=attempt.name,reasoner=reasoner,layout=layout,phase=phase,
                        preparations=len(g['runs']),preparations_completed=prepared,
                        catalog_requests=attempted,catalog_requests_completed=attempted-failed))
                    for ax,success,n in ((axes[0],prepared,len(g['runs'])),(axes[1],attempted-failed,attempted)):
                        if n:
                            ax.bar(i+offset,success/n*100,width=.34,color=COLORS[phase])
                            ax.text(i+offset,success/n*100+3,f'{success}/{n}',ha='center',fontsize=9)
                        else:
                            ax.text(i+offset,5,'Not\nattempted',ha='center',fontsize=8)
            for ax,title in zip(axes,('Preparation completion','Catalog request completion')):
                ax.set(title=title,ylabel='Completed (%)',ylim=(0,116),xlim=(-.6,1.6))
                ax.set_yticks([0,25,50,75,100]);ax.set_xticks([0,1],['Distributed','Replicated'])
                ax.grid(axis='y',alpha=.2);ax.set_axisbelow(True)
            axes[0].legend(handles=[Patch(color=c,label=k) for k,c in COLORS.items()],loc='upper right')
            fig.suptitle(description+f' / {reasoner}\nReplicated after-values belong to the same adaptation trial, not a separate replicated adaptation.',fontsize=11)
            save_figure(fig,figures,tag+'-completion.png',manifest)

            levels = sorted({int(r['concurrency']) for g in groups.values() for r in g['queries']})
            fig, axes = plt.subplots(2,3,figsize=(13,7),layout='constrained',squeeze=False)
            for i,layout in enumerate(('distributed','replicated')):
                for phase in COLORS:
                    series = [[],[],[]]
                    for level in levels:
                        selected = [r for r in groups[phase,layout]['queries'] if int(r['concurrency'])==level]
                        n = sum(int(r['client_requests']) for r in selected)
                        failed = sum(int(r['error_count']) for r in selected)
                        latency = [number(r['latency_p95_ms'])/1000 for r in selected if int(r['client_requests'])>int(r['error_count'])]
                        latency = [v for v in latency if math.isfinite(v)]
                        throughput = [(int(r['client_requests'])-int(r['error_count']))*1000/float(r['query_wall_ms']) for r in selected if float(r['query_wall_ms'])>0]
                        values = [(n-failed)/n*100 if n else math.nan,
                                  statistics.median(latency) if latency else math.nan,
                                  statistics.median(throughput) if throughput else math.nan]
                        for seq,value in zip(series,values):seq.append(value)
                        concurrency_data.append(dict(attempt=attempt.name,reasoner=reasoner,layout=layout,phase=phase,
                            concurrency=level,requests=n,failures=failed,completion_percent=values[0],
                            median_within_run_successful_p95_seconds=values[1],median_successful_catalog_requests_s=values[2]))
                        if n:
                            axes[i,0].annotate(f'{n-failed}/{n}',(level,values[0]),xytext=(0,6 if phase=='After adaptation' else 18),textcoords='offset points',ha='center',fontsize=8,color=COLORS[phase])
                    for j,values in enumerate(series):
                        axes[i,j].plot(levels,values,'o-',label=phase,color=COLORS[phase])
                        if not any(math.isfinite(v) for v in values):
                            axes[i,j].text(.03,.13 if phase=='Baseline' else .05,phase+': no valid samples',transform=axes[i,j].transAxes,va='top',fontsize=8,color=COLORS[phase])
                for j,title in enumerate(('Completion (%)','Successful-request p95 (s)','Successful catalog requests / s')):
                    axes[i,j].set(title=f'{layout.capitalize()} — {title}',xlabel='Concurrent catalog requests',xticks=levels)
                    axes[i,j].grid(alpha=.2)
                axes[i,0].set_ylim(-2,125)
                axes[i,1].set_ylim(bottom=0)
                axes[i,2].set_ylim(bottom=0)
                if not any(int(r['client_requests'])>int(r['error_count']) for phase in COLORS for r in groups[phase,layout]['queries']):
                    axes[i,1].set_yticks([])
                    axes[i,1].set_ylim(0,1)
            axes[0,2].legend()
            fig.suptitle(description+f' / {reasoner}\nLatency excludes failed requests; points are medians of within-run p95, not a pooled p95. No requests ≠ zero throughput.',fontsize=10)
            save_figure(fig,figures,tag+'-concurrency.png',manifest)

            nodes = sorted({r['node_id'] for g in groups.values() for r in g['nodes']})
            fig,axes=plt.subplots(2,2,figsize=(12,7),layout='constrained',sharey='col')
            for i,layout in enumerate(('distributed','replicated')):
                for j,(metric,factor,title) in enumerate((('process_cpu_ms',.001,'Preparation CPU (s)'),('current_rss_kib',1/1024,'Preparation process RSS (MiB)'))):
                    ax=axes[i,j]
                    for phase,offset in [('Baseline',-.12),('After adaptation',.12)]:
                        for k,node in enumerate(nodes):
                            values=[number(r[metric])*factor for r in groups[phase,layout]['nodes'] if r['node_id']==node]
                            values=[v for v in values if math.isfinite(v)]
                            if values:
                                mid=statistics.median(values)
                                ax.errorbar(k+offset,mid,yerr=[[mid-min(values)],[max(values)-mid]],fmt='o',color=COLORS[phase],capsize=3)
                                node_data.append(dict(attempt=attempt.name,reasoner=reasoner,layout=layout,phase=phase,node=node,
                                    metric=metric,samples=len(values),median=mid,minimum=min(values),maximum=max(values)))
                            else:ax.text(k+offset,.02,'NA',transform=ax.get_xaxis_transform(),ha='center',fontsize=7,color=COLORS[phase])
                    ax.set(title=f'{layout.capitalize()} — {title}',xticks=range(len(nodes)),xlim=(-.6,len(nodes)-.4),ylim=(0,None))
                    ax.set_xticklabels(nodes,rotation=30,ha='right');ax.grid(axis='y',alpha=.2)
            for j,(metric,factor) in enumerate((('process_cpu_ms',.001),('current_rss_kib',1/1024))):
                upper=max((number(r.get(metric))*factor for g in groups.values() for r in g['nodes'] if math.isfinite(number(r.get(metric)))), default=1)
                axes[0,j].set_ylim(0,max(1,upper*1.08))
            axes[0,0].legend(handles=[Patch(color=c,label=k) for k,c in COLORS.items()])
            fig.suptitle(description+f' / {reasoner}\nLogical participants; completed preparations only. Median and observed range, not confidence intervals.',fontsize=11)
            save_figure(fig,figures,tag+'-node-costs.png',manifest)
        sample_file=attempt/'service-samples.jsonl'
        if sample_file.exists():
            samples=[json.loads(line) for line in sample_file.read_text().splitlines() if line.strip()]
            origin=min(datetime.fromisoformat(r['time']) for r in samples) if samples else None
            for sample in samples:
                resources=json_rows(sample.get('resources',''))
                cpu=[number(r.get('CPUPerc','').rstrip('%')) for r in resources]
                ram=[memory_mib(r.get('MemUsage','')) for r in resources]
                telemetry.append(dict(attempt=attempt.name,host=sample['host'],time=sample['time'],
                    elapsed_minutes=(datetime.fromisoformat(sample['time'])-origin).total_seconds()/60,
                    containers=len(resources),cpu_percent=sum(cpu) if cpu else math.nan,
                    docker_memory_mib=sum(ram) if ram else math.nan,error=sample.get('error','')))
            selected=[r for r in telemetry if r['attempt']==attempt.name]
            if selected:
                fig,axes=plt.subplots(2,1,figsize=(12,6),sharex=True,layout='constrained')
                for host in sorted({r['host'] for r in selected}):
                    rows=sorted((r for r in selected if r['host']==host),key=lambda r:r['elapsed_minutes'])
                    for ax,key in zip(axes,('cpu_percent','docker_memory_mib')):
                        ax.plot([r['elapsed_minutes'] for r in rows],[r[key] for r in rows],label=host,linewidth=1)
                axes[0].set(ylabel='Sum of container CPU (%)',ylim=(0,None));axes[0].legend(ncol=5)
                axes[1].set(ylabel='Docker memory usage (MiB)',xlabel='Minutes since first recovery telemetry sample',ylim=(0,None))
                for ax in axes:ax.grid(alpha=.2)
                fig.suptitle(description+'\nRecovery telemetry only, including warm-up and both layouts. 100% CPU = one core; memory is not process RSS.',fontsize=11)
                save_figure(fig,figures,attempt.name+'-infrastructure.png',manifest)
                hosts=sorted({r['host'] for r in selected})
                fig,axes=plt.subplots(len(hosts),2,figsize=(12,2*len(hosts)),sharex=True,sharey='col',layout='constrained',squeeze=False)
                for i,host in enumerate(hosts):
                    rows=sorted((r for r in selected if r['host']==host),key=lambda r:r['elapsed_minutes'])
                    for j,(key,label) in enumerate((('cpu_percent','Container CPU (%)'),('docker_memory_mib','Docker memory (MiB)'))):
                        axes[i,j].plot([r['elapsed_minutes'] for r in rows],[r[key] for r in rows],color='#0072B2',linewidth=1)
                        axes[i,j].set_title(host+' — '+label)
                        axes[i,j].set_ylim(bottom=0); axes[i,j].grid(alpha=.2)
                for j,key in enumerate(('cpu_percent','docker_memory_mib')):
                    upper=max((r[key] for r in selected if math.isfinite(r[key])),default=1)
                    axes[0,j].set_ylim(0,max(1,upper*1.08))
                for ax in axes[-1]:ax.set_xlabel('Minutes since first recovery telemetry sample')
                fig.suptitle(description+'\nPhysical hosts, shared scales; sums cover recovery containers only, not whole-host utilization.',fontsize=11)
                save_figure(fig,figures,attempt.name+'-infrastructure-per-host.png',manifest)
    write_csv(analysis/'baseline-recovery-comparison.csv',totals)
    write_csv(analysis/'concurrency-comparison.csv',concurrency_data)
    write_csv(analysis/'node-cost-comparison.csv',node_data)
    write_csv(analysis/'service-resource-timeseries.csv',telemetry)
    from .docker_figures import docker_figures
    manifest.extend(docker_figures(directory, baseline, decisions, figures))
    from .paired_figures import paired_figures
    manifest.extend(paired_figures(directory, baseline, decisions, figures))
    (figures/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    text='''# Baseline versus recorded adaptation

Figures are in `../figures/`; their manifest lists every generated PNG. CSVs in this directory preserve denominators, strata and sample counts. Raw evidence is unchanged.

## Recorded actions

'''+ '\n'.join('- '+note for note in notes)+'''

## Interpretation

Completion compares recorded preparations and complete catalog requests. Missing requests are not successes or zero-cost measurements. Replicated measurements inside a distributed adaptation trial are retained, explicitly labelled; they are not evidence that the supervisor executed a separate replicated recovery. An abstention remains an abstention.

Latency includes successful requests only. P95 values are medians of run-level quantiles, not a pooled tail estimate, and are weakly estimated with few requests. Node preparation plots show conditional costs from successful preparations, with observed ranges rather than confidence intervals. Recovery telemetry covers warm-up and both verification layouts and has no equivalent continuously sampled baseline in this archive. Do not use it as a before/after resource reduction claim.

A placement intervention may improve preparation without restoring service-level success. Restart effects, changing host load, limited repetitions and unequal successful sample counts prevent a causal superiority claim. Missing replicated reference validation does not prove semantic inconsistency or equivalence. Deployment duration and complete experiment duration are not production recovery time.
'''
    (analysis/'COMPARISON.md').write_text(text)
    with (directory/'README.md').open('a') as f:
        marker='\nDetailed baseline/adaptation figures: `figures/manifest.json`. Interpretation and source tables: `analysis/COMPARISON.md`.\n'
        if marker.strip() not in (directory/'README.md').read_text():f.write(marker)
    return figures


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input-dir',type=Path,required=True)
    args=parser.parse_args()
    print(comparison(args.input_dir))
